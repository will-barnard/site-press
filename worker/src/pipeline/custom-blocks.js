import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { config } from '../config.js';
import { loadCatalog } from './catalog.js';
import { coverage } from './text.js';
import { toHex } from './analyze.js';

// For sections that no library block fits, ask dry-dock's coder pool to
// write a site-specific block (component + schema) into site/blocks/.
//
// The model only writes the template and CSS. The <script> is ours, fixed,
// and the component can only reach what the template compiler allows — so
// a bad generation can look wrong but can't do anything. Every result is
// compiled, checked against its own schema, and checked for dropped text
// before it replaces the placeholder; anything that fails stays a
// placeholder, which still shows all of the section's content.

const FIELD_TYPES = new Set(['text', 'textarea', 'richtext', 'media', 'link', 'select', 'boolean', 'number', 'color', 'list']);
const FORBIDDEN_TEMPLATE = /<script|<style|v-html|\son[a-z]+\s*=|javascript:|https?:\/\/|\$el|window\.|document\./i;
const FORBIDDEN_CSS = /@import|url\(|expression\(|<\/style|position:\s*fixed/i;

let compiler = null;
function sfcCompiler() {
  if (!compiler) compiler = createRequire(path.join(config.templateDeps, 'noop.js'))('vue/compiler-sfc');
  return compiler;
}

const SYSTEM = `You write ONE Vue 3 section component for a small website CMS, reproducing one section of an existing site.
Answer with a single JSON object and nothing else:
{
  "name": "short-kebab-case-name describing the layout, e.g. stats-row",
  "label": "Human readable name",
  "fields": { "<prop name>": { "type": "<field type>", "label": "<label>" } },
  "props": { "<prop name>": <this section's value> },
  "template": "<div class=\\"sp-container ...\\">...</div>",
  "css": "scoped CSS for the classes in the template"
}
Field types: text, textarea, richtext, media, link (value {"label","href"}), select (needs "options": [...]), boolean, number, list (needs "fields": {...} describing each item).
Template rules:
- Read every value from \`content\`: {{ content.heading }}, v-for="(item, i) in content.items" :key="i".
- Images: <SpMedia :value="content.photo" />. Rich text: <SpRichText :html="content.body" />. A link: <SpLink :to="content.cta.href">{{ content.cta.label }}</SpLink>. A list of buttons ({link} items): <SpButtons :buttons="content.buttons" />.
- Never use <script>, v-html, inline event handlers, or any URL.
- One root element: <div class="sp-container ...">. It must collapse to a single column below 768px (add a @media (max-width: 767px) rule).
- Use the theme's CSS variables instead of fixed fonts/colours: var(--sp-gap), var(--sp-radius), var(--sp-font-heading), var(--sp-h2-size), var(--sp-h3-size), var(--sp-color-link). The section's background colour is applied outside the component.
Props rules:
- Copy every piece of visible text exactly; never invent or summarise.
- Media values are image ids from the input such as "img_2"; links are {"label","href"} with hrefs copied exactly.`;

function checkFields(fields, where = 'fields') {
  const errs = [];
  if (!fields || typeof fields !== 'object' || Array.isArray(fields)) return [`${where} must be an object`];
  for (const [k, f] of Object.entries(fields)) {
    if (!/^[a-zA-Z][a-zA-Z0-9_]*$/.test(k)) errs.push(`${where}.${k}: prop names must be simple identifiers`);
    if (!f || !FIELD_TYPES.has(f.type)) { errs.push(`${where}.${k}: type must be one of ${[...FIELD_TYPES].join(', ')}`); continue; }
    if (f.type === 'select' && !(Array.isArray(f.options) && f.options.length)) errs.push(`${where}.${k}: select needs options`);
    if (f.type === 'list') errs.push(...checkFields(f.fields, `${where}.${k}.fields`));
  }
  return errs;
}

function sfcSource({ template, css, sourceNote }) {
  return `<script setup>
// ${sourceNote}
// Generated by site-press. This file belongs to the site now: edit it freely,
// site-press never writes into site/blocks after generation.
defineProps({ content: { type: Object, required: true }, variant: { type: String, default: 'default' } });
</script>

<template>
  ${template.trim()}
</template>

<style scoped>
${css.trim()}
</style>
`;
}

export async function generateCustomBlocks({ mapped, pagesData, outDir, drydock, log, checkCancel, limit = 12 }) {
  const { shared } = await loadCatalog();
  const made = [];
  const taken = new Set();
  let attempted = 0;

  for (const page of mapped.pages) {
    const data = pagesData[page.key];
    for (const [bi, block] of page.blocks.entries()) {
      if (block.type !== 'placeholder') continue;
      if (!drydock.enabled) return made;
      if (attempted >= limit) { log.info(`custom block limit (${limit}) reached; remaining placeholders stay as they are`); return made; }
      await checkCancel();
      attempted++;
      const section = data.sections[block._meta.section];
      const byId = Object.fromEntries(data.images.map((i) => [i.id, i]));
      const prompt = [
        `Section ${section.idx + 1} of ${data.sections.length} on ${page.sourcePath}. Size ${section.bbox.w}x${section.bbox.h}px.`,
        `Background: ${toHex(section.bg) || 'page default'}${section.bgImage ? ', has a background photo' : ''}. Text is ${section.centered ? 'mostly centered' : 'left aligned'}.`,
        `Images (id, size, position in the section): ${section.images.map((i) => `${i.id} ${i.w}x${i.h} at ${i.x},${i.y}`).join('; ') || 'none'}.`,
        `Heading sizes on the original: ${section.flow.filter((f) => f.kind === 'h').map((f) => `${Math.round(f.size || 0)}px "${f.text.slice(0, 40)}"`).join(', ') || 'none'}.`,
        '',
        'Section HTML:',
        section.simplified,
      ].join('\n');

      let compiled = null;
      const check = (obj) => {
        const errs = [];
        if (!obj || typeof obj !== 'object') return ['answer must be a JSON object'];
        if (!/^[a-z][a-z0-9-]{2,30}$/.test(obj.name || '')) errs.push('"name" must be kebab-case, 3-30 characters');
        errs.push(...checkFields(obj.fields));
        if (typeof obj.template !== 'string' || !obj.template.trim().startsWith('<')) errs.push('"template" must be an HTML string');
        if (typeof obj.css !== 'string') errs.push('"css" must be a string');
        if (errs.length) return errs;
        if (FORBIDDEN_TEMPLATE.test(obj.template)) errs.push('template uses something forbidden (script, v-html, event handlers, URLs, window/document)');
        if (FORBIDDEN_CSS.test(obj.css)) errs.push('css uses something forbidden (@import, url(), position: fixed)');
        const used = new Set([...obj.template.matchAll(/content\.([A-Za-z_]\w*)/g)].map((m) => m[1]));
        const unknown = [...used].filter((k) => !(k in obj.fields));
        if (unknown.length) errs.push(`template reads props that aren't in fields: ${unknown.join(', ')}`);
        const schema = { fields: obj.fields };
        const { value, errors } = shared.validateProps(schema, obj.props);
        errs.push(...errors.slice(0, 6));
        shared.walkMedia(schema.fields, value, (v) => { if (!byId[v.src]) errs.push(`unknown image id "${v.src}"`); });
        const cov = coverage(section.text, shared.collectText(schema.fields, value).join(' '));
        if (cov.score < 0.85) errs.push(`props are missing text (${Math.round(cov.score * 100)}% kept). Include: ${cov.missing.slice(0, 15).join(', ')}`);
        const res = sfcCompiler().compileTemplate({ source: obj.template, id: 'x', filename: 'block.vue' });
        if (res.errors.length) errs.push(...res.errors.slice(0, 3).map((e) => `template does not compile: ${e.message || e}`));
        if (!errs.length) compiled = { value };
        return errs;
      };

      try {
        const out = await drydock.json({ system: SYSTEM, prompt, check });
        const obj = out.value;
        let name = `x-${obj.name}`;
        while (taken.has(name)) name = `${name}-2`;
        taken.add(name);
        const schema = { type: name, label: obj.label || obj.name, description: `Generated for ${page.sourcePath} section ${section.idx + 1}`, variants: ['default'], fields: obj.fields };
        const props = compiled.value;
        shared.walkMedia(schema.fields, props, (v, set) => {
          const im = byId[v.src];
          set({ src: im.src, alt: im.alt || '', width: im.w || undefined, height: im.h || undefined });
        });
        const dir = path.join(outDir, 'site/blocks', name);
        await fs.mkdir(dir, { recursive: true });
        await fs.writeFile(path.join(dir, 'schema.js'), `// Generated by site-press for ${page.sourceUrl}, section ${section.idx + 1}.\nexport default ${JSON.stringify(schema, null, 2)};\n`);
        await fs.writeFile(path.join(dir, 'index.vue'), sfcSource({ template: obj.template, css: obj.css, sourceNote: `Rebuilt from ${page.sourceUrl}, section ${section.idx + 1}.` }));
        const style = block.props._style;
        page.blocks[bi] = {
          type: name, variant: 'default', props: { ...props, ...(style ? { _style: style } : {}) }, _schema: schema, _restore: block,
          _meta: { ...block._meta, source: 'custom', reason: `custom block written by dry-dock (${out.worker})`, previous: 'placeholder', coverage: block._meta.coverage },
        };
        made.push({ name, page: page.path, section: section.idx, worker: out.worker, dir });
        log.info(`  ${page.path} section ${section.idx + 1}: generated custom block ${name} (${out.worker})`);
      } catch (err) {
        log.warn(`  ${page.path} section ${section.idx + 1}: custom block failed (${err.kind || 'error'}: ${err.message}) — kept as a placeholder`);
      }
    }
  }
  return made;
}

// If a generated block breaks the build anyway, put the placeholders back.
export async function revertCustomBlocks({ mapped, outDir, made, log, only }) {
  const names = new Set((only || made).map((m) => m.name));
  for (const page of mapped.pages) {
    page.blocks = page.blocks.map((b) => (names.has(b.type) && b._restore ? b._restore : b));
  }
  for (const n of names) await fs.rm(path.join(outDir, 'site/blocks', n), { recursive: true, force: true });
  log.warn(`reverted ${names.size} custom block(s) to placeholders`);
}
